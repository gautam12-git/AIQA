function cov(
  p: [number, number],
  b: [number, number],
  f: [number, number],
  a: [number, number],
  w: [number, number],
): Coverage {
  return {
    pages: { label: "Pages", discovered: p[0], tested: p[1] },
    buttons: { label: "Buttons", discovered: b[0], tested: b[1] },
    forms: { label: "Forms", discovered: f[0], tested: f[1] },
    apis: { label: "API endpoints", discovered: a[0], tested: a[1] },
    workflows: { label: "Workflows", discovered: w[0], tested: w[1] },
  };
}

