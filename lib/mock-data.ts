export function computeDashboardStats(): DashboardStats {
  const bySeverity = { P0: 0, P1: 0, P2: 0, P3: 0 };
  for (const b of bugs) {
    if (b.status !== "dismissed" && b.status !== "fixed") bySeverity[b.severity]++;
  }
  const avgCoverage = Math.round(
    projects.reduce((sum, p) => {
      const c = p.coverage;
      const pct =
        ((c.pages.tested + c.buttons.tested + c.forms.tested + c.apis.tested + c.workflows.tested) /
          (c.pages.discovered + c.buttons.discovered + c.forms.discovered + c.apis.discovered + c.workflows.discovered)) *
        100;
      return sum + pct;
    }, 0) / projects.length,
  );

  return {
    projects: projects.length,
    activeRuns: runs.filter((r) => r.status === "running" || r.status === "queued").length,
    totalBugs: bugs.filter((b) => b.status !== "dismissed" && b.status !== "fixed").length,
    bugsBySeverity: bySeverity,
    regressions: bugs.filter((b) => b.isRegression).length,
    apiHealth: 78,
    securityFindings: bugs.filter((b) => b.category === "security").length,
    a11yIssues: bugs.filter((b) => b.category === "accessibility").length,
    avgCoverage,
    perfScore: 84,
  };
}
